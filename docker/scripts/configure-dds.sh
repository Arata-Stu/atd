#!/usr/bin/env bash
# Root startup task. Docker ENV also supplies these settings to docker exec.
set -euo pipefail

if [[ "$(id -u)" != 0 ]]; then
    printf 'DDS 設定はコンテナの root 起動処理で実行してください。\n' >&2
    exit 1
fi

task_script_dir="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
task_source="${ATD_DDS_PROFILE_SOURCE:-${task_script_dir}/../middleware_profiles/fastdds.xml}"
task_config_dir="${ATD_DDS_CONFIG_DIR:-/etc/atd}"
[[ "$task_config_dir" = /* ]] || { printf 'DDS 設定先は絶対パスが必要です。\n' >&2; exit 1; }
[[ -f "$task_source" && -r "$task_source" ]] || { printf 'DDS プロファイルを読めません: %s\n' "$task_source" >&2; exit 1; }

mkdir -p -- "$task_config_dir"
task_config_dir="$(CDPATH= cd -- "$task_config_dir" && pwd -P)"
task_profile="${task_config_dir}/fastdds.xml"
task_env="${task_config_dir}/dds.env.sh"
task_xml_temp=""
task_env_temp=""
trap '[[ -z "$task_xml_temp" ]] || rm -f -- "$task_xml_temp"; [[ -z "$task_env_temp" ]] || rm -f -- "$task_env_temp"' EXIT

# Leave unchanged files in place; never start ROS with a partly copied profile.
if ! cmp -s -- "$task_source" "$task_profile"; then
    task_xml_temp="$(mktemp "${task_config_dir}/.fastdds.XXXXXX")"
    install -m 0644 -- "$task_source" "$task_xml_temp"
    mv -f -- "$task_xml_temp" "$task_profile"
    task_xml_temp=""
fi
chmod 0644 "$task_profile"

task_env_temp="$(mktemp "${task_config_dir}/.dds-env.XXXXXX")"
{
    printf '# Generated by configure-dds.sh; source from Bash when opening a shell.\n'
    printf 'export RMW_IMPLEMENTATION=rmw_fastrtps_cpp\n'
    printf 'export FASTDDS_DEFAULT_PROFILES_FILE=%q\n' "$task_profile"
    printf 'export ROS_AUTOMATIC_DISCOVERY_RANGE=SYSTEM_DEFAULT\n'
    printf "export ROS_STATIC_PEERS=''\n"
    printf 'export RMW_FASTRTPS_USE_QOS_FROM_XML=0\n'
    printf 'unset CYCLONEDDS_URI FASTRTPS_DEFAULT_PROFILES_FILE ROS_DISCOVERY_SERVER\n'
    printf 'unset FASTDDS_ENVIRONMENT_FILE ROS_LOCALHOST_ONLY SKIP_DEFAULT_XML\n'
} > "$task_env_temp"
chmod 0644 "$task_env_temp"
if ! cmp -s -- "$task_env_temp" "$task_env"; then
    mv -f -- "$task_env_temp" "$task_env"
    task_env_temp=""
fi
chmod 0644 "$task_env"
printf 'DDS: Fast DDS / UDPv4 / 127.0.0.1 (%s)\n' "$task_profile"
